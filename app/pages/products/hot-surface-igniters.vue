        <div class="sec-num">06 · Engineering FAQ</div>
        <h2>The questions <span class="accent">we get most</span>.</h2>
        <div class="faq-grid">
          <div class="faq-item">
            <div class="faq-q">
              What is the difference between Gas HSI and Fuel HSI?
            </div>
            <div class="faq-a">
              The ceramic element and electrical construction are identical. The
              difference is the environmental and duty cycle rating. Gas HSI is
              rated for dry, clean indoor environments at 5–15 cycles/day. Fuel
              HSI is rated for condensate-rich, ash/particulate environments at
              15,000–20,000 cycles/heating season. If in doubt, specify Fuel HSI
              — it handles both duty profiles.
            </div>
          </div>
          <div class="faq-item">
            <div class="faq-q">
              Can HSI/120 and HSI/230 replace my existing Al₂O₃ igniter?
            </div>
            <div class="faq-a">
              In most gas furnace and pellet stove applications, yes — the HSI is
              a direct mechanical and electrical drop-in for the common Al₂O₃
              platforms (Norton, White-Rodgers, Robertshaw). Send your current
              part number and we confirm dimensions and wiring before shipping
              samples. Fitment confirmation in 24 hours.
            </div>
          </div>
          <div class="faq-item">
            <div class="faq-q">
              Why does the Fuel HSI last so much longer than Al₂O₃ in pellet
              stoves?
            </div>
            <div class="faq-a">
