            <div class="fail-num">01</div>
            <div class="fail-name">Thermal Shock Cracking</div>
            <div class="fail-desc">
              Repeated rapid temperature cycles from ambient (or sub-zero) to
              1,100°C accumulate micro-cracks in the ceramic matrix. Alumina's
              lower fracture toughness means these grow faster. Failure is
              sudden, typically mid-season.
            </div>
            <div class="fail-solution">
              Si₃N₄ fix → 4–6× higher fracture toughness. Micro-cracks don't
              propagate at operating stress levels.
            </div>
          </div>
          <div class="fail-card">
            <div class="fail-num">02</div>
            <div class="fail-name">
              Electrode Oxidation &amp; Resistance Drift
            </div>
            <div class="fail-desc">
              The heating element's cold resistance drifts above spec as
              electrode oxidation builds up over thermal cycles. The igniter
              still heats, but more slowly — missing the pellet ignition window.
            </div>
            <div class="fail-solution">
              Si₃N₄ fix → More stable resistance characteristics across thermal
              cycling range. Cold resistance drift within spec at 100K cycles.
            </div>
          </div>
          <div class="fail-card">
            <div class="fail-num">03</div>
            <div class="fail-name">Cold-Start Insulation Breakdown</div>
            <div class="fail-desc">
              At very low ambient temperatures, absorbed moisture in the ceramic
              body can reduce insulation resistance below the 100 MΩ minimum,
              causing nuisance trips or no-fire conditions.
            </div>
            <div class="fail-solution">
              Si₃N₄ fix → Lower moisture absorption than alumina. BLK
              insulation resistance holds ≥100 MΩ @ 500V DC down to −40°C.
            </div>
