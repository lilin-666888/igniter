        <div class="faq-grid">
          <div class="faq-item">
            <div class="faq-q">
              Why is zirconia so much tougher than other ceramics?
            </div>
            <div class="faq-a">
              Transformation toughening. ZrO₂ exists in tetragonal phase at room
              temperature; when a crack tries to propagate, the stress at the
              crack tip triggers tetragonal → monoclinic phase transformation,
              which expands 4% volume and physically closes the crack. Other
              oxides don't have this mechanism.
            </div>
          </div>
          <div class="faq-item">
            <div class="faq-q">
              What's "low-temperature degradation" and should I worry?
            </div>
            <div class="faq-a">
              Y-TZP can undergo slow tetragonal → monoclinic transformation in
              wet environments at 100–400°C, causing surface microcracks and
              strength loss over years. For continuous wet service, use Ce-TZP
              variant which is immune. Dry service or short wet exposure: Y-TZP
              is fine.
            </div>
          </div>
          <div class="faq-item">
            <div class="faq-q">
              Can you supply medical-grade biocompatible zirconia?
            </div>
            <div class="faq-a">
              Yes — Y-TZP-A grade (ISO 13356 compliant) is available for dental
              restoration, orthopedic, and medical instrument applications. We
              supply medical instrument OEMs and can provide biocompatibility
              test reports on request.
            </div>
          </div>
          <div class="faq-item">
            <div class="faq-q">
              ZrO₂ vs Si₃N₄ for ball bearings — which wins?
            </div>
            <div class="faq-a">
              Depends on duty: ZrO₂ is denser (6.0 vs 3.2 g/cm³) — better for
              impact-loaded applications. Si₃N₄ is lighter and harder — better
              for high-RPM hybrid bearings where centrifugal load matters. For
              most high-speed bearings, Si₃N₄ wins; for impact and corrosion
              service, ZrO₂.
            </div>
