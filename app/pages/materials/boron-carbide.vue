            <div class="faq-q">
              Why does B₄C oxidize at relatively low temperatures?
            </div>
            <div class="faq-a">
              B₄C begins surface oxidation around 500°C in air, forming boric
              oxide (B₂O₃) which evaporates above 1000°C — so unlike SiC, B₄C
              has no self-protective oxide layer. For air service above 500°C,
              switch to alumina or SiC. For inert-atmosphere service, B₄C is
              stable to 1800°C.
