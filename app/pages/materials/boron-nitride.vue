        <div class="faq-grid">
          <div class="faq-item">
            <div class="faq-q">h-BN vs PBN — which one for my application?</div>
            <div class="faq-a">h-BN (hot-pressed) for general high-temp insulator and crucible service — machinable, lower cost. PBN (pyrolytic) for semiconductor plasma applications and aerospace insulators where the highest purity and electrical performance is required. PBN is 3–5× more expensive than h-BN.</div>
          </div>
          <div class="faq-item">
            <div class="faq-q">Can BN really be machined with conventional carbide tooling?</div>
            <div class="faq-a">Yes — h-BN machines very much like graphite with conventional carbide drills, mills, and lathes. No diamond tooling required. Tight tolerances (±0.05 mm) are achievable. This is the single biggest cost advantage of BN over other high-temperature ceramics for custom geometries.</div>
          </div>
          <div class="faq-item">
            <div class="faq-q">How does BN compare to graphite as a release agent?</div>
            <div class="faq-a">BN replaces graphite where (a) electrical insulation is required, (b) carbon contamination of the workpiece is unacceptable, or (c) service temperature in air exceeds graphite's 400°C oxidation limit. BN releases cost more upfront but reduce defects and rework in glass/metal forming.</div>
          </div>
          <div class="faq-item">
            <div class="faq-q">Why is PBN thermal conductivity so anisotropic?</div>
            <div class="faq-a">PBN's hexagonal layered structure deposits with strong directional ordering — heat moves easily along the basal planes (~62 W/m·K) and poorly through-plane (~2 W/m·K). Designers can use this as a feature: route heat where you want it, insulate where you don't.</div>
          </div>
          <div class="faq-item">
            <div class="faq-q">Is BN hygroscopic? Does it absorb moisture?</div>
            <div class="faq-a">Yes — porous h-BN absorbs atmospheric moisture, which can release as steam during the first heat-up. We recommend pre-baking BN parts at 200–300°C under vacuum before installation in moisture-sensitive equipment. PBN is fully-dense and not hygroscopic.</div>
          </div>
          <div class="faq-item">
            <div class="faq-q">What's the MOQ for custom BN parts?</div>
            <div class="faq-a">Custom-machined h-BN parts: 10-piece MOQ for prototypes, 50+ for production. Stock crucibles and evaporation boats: no MOQ. Custom PBN parts: case-by-case quote, typically 5+ pieces for prototype due to high tooling cost. Lead time 3–6 weeks for h-BN, 6–10 weeks for PBN.</div>
