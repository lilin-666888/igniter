            <div class="guide-num">QUESTION 02</div>
            <div class="guide-q">I need an electrical insulator that also dissipates heat fast.</div>
            <div class="guide-a">Standard ceramics insulate but trap heat. AlN flips that — 170 W/m·K thermal conductivity (10× alumina) with full dielectric isolation. The default for power electronics and LED submounts.</div>
            <div class="guide-pick">→ Pick AlN</div>
          </div>

          <div class="guide-card">
            <div class="guide-num">QUESTION 03</div>
            <div class="guide-q">Abrasive slurry chewing through my pump seals. What lasts longest?</div>
            <div class="guide-a">SiC at HV 2800 is the hardest engineering ceramic short of diamond. Combined with chemical inertness, it's the industry default for pump seal faces in mining, chemical, and oil & gas service.</div>
            <div class="guide-pick">→ Pick SiC</div>
          </div>

