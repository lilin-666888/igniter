    <h2 id="when-to-use">When to Use Each Material</h2>
    <p>The decision framework is not complex. Answer these three questions:</p>

    <h3>1. How many cycles per year?</h3>
    <p>The thermal fatigue damage is cumulative and proportional to cycle count. Below 5,000 cycles/year (residential gas furnace, standard duty), Al₂O₃ will typically reach a 5–7 year field life — adequate for most residential heating applications. Above 10,000 cycles/year (pellet stoves, commercial HVAC), Si₃N₄ is the only reliable specification.</p>

    <h3>2. What is the cold-start temperature delta?</h3>
    <p>The critical thermal shock occurs at ignition start — the higher the starting temperature delta (ambient to 1,100°C), the more stress is imposed per cycle. A residential gas furnace in a conditioned mechanical room starts from +15°C. A pellet stove in a Northern European utility room starts from −5°C. That additional 20°C ambient differential, multiplied across 15,000 cycles per year, is the primary driver of elevated Al₂O₃ failure rates in high-latitude pellet stove markets.</p>

    <h3>3. What does one warranty return cost you?</h3>
    <p>For an OEM shipping 100,000 units/year at a 3% warranty return rate, the annual warranty expense is 3,000 field service events. At €150 per service event (call-out, part, labour), that is €450,000/year. A 1 percentage point reduction in warranty rate saves €150,000/year — which more than offsets the unit cost premium of Si₃N₄ at most production volumes above 50,000 units/year.</p>

