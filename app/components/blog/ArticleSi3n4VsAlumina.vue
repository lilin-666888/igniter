    <p>The numbers that matter most for igniter longevity are <strong>fracture toughness and thermal shock resistance</strong> — not maximum operating temperature. Both materials reach adequate surface temperature for gas ignition. The question is how many thermal cycles they can sustain before micro-cracking leads to failure.</p>

    <h3>Why Fracture Toughness Matters More Than Operating Temperature</h3>
    <p>Every ignition cycle imposes a thermal shock. From ambient (or sub-zero in a pellet stove control cabinet) to 1,100°C in 3 seconds, then back to ambient in the next 30 seconds. Each cycle creates and propagates micro-cracks in the ceramic matrix.</p>
    <p>Al₂O₃ at KIC 3–4 MPa·m½ propagates these cracks much faster than Si₃N₄ at 6–7 MPa·m½. The result is not a gradual performance decline — it is a sudden fracture event, typically occurring after 20,000–40,000 cycles in Al₂O₃, vs 100,000+ cycles in Si₃N₄ under the same conditions.</p>

